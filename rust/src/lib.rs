//! VON core.
//!
//! Everything below the Flutter UI lives here: project sandboxing, the agent
//! loop, local (`llama.cpp`) and cloud inference, code execution, the localhost
//! preview server, and the "anti-blast" resource governor.
//!
//! The `api` module is the only surface exposed to Dart; `flutter_rust_bridge`
//! generates `frb_generated.rs` from it at build time.

/// The Dart-facing layer, behind a feature because it cannot compile without
/// `frb_generated.rs` — `StreamSink` is a *generated* type alias, not something
/// the `flutter_rust_bridge` runtime crate exports, so no hand-written stub can
/// stand in for it. Disabled, `cargo test` type-checks everything below the
/// bridge without needing codegen first; the APK build enables it and checks
/// the full surface.
#[cfg(feature = "ffi")]
pub mod api;
pub mod db;
pub mod error;
pub mod executor;
pub mod github;
pub mod governor;
pub mod llm;
pub mod sandbox;
pub mod server;
pub mod state;

pub mod agent;

/// Generated by `flutter_rust_bridge_codegen generate` (see
/// `flutter_rust_bridge.yaml`), which is why it is gitignored. It also defines
/// the `StreamSink` alias the `api` module imports.
#[cfg(feature = "ffi")]
#[allow(clippy::all, unused_imports, dead_code, non_snake_case)]
mod frb_generated;

pub use error::{Result, VonError};
