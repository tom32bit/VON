/// The single seam between the Flutter app and the Rust core.
///
/// Everything UI-side calls this rather than importing `src/rust/**` directly.
/// `src/rust/**` is generated by `flutter_rust_bridge_codegen` at build time and
/// is not checked in, so keeping the surface in one file means a bridge change
/// breaks one place instead of thirty.
class CoreApi {
  const CoreApi._();
  static const instance = CoreApi._();

  static bool _initialised = false;

  /// Loads the native library and boots the Rust core. Safe to call twice —
  /// Android can recreate the Flutter engine without restarting the process.
  static Future<void> ensureInitialised() async {
    if (_initialised) return;
    await RustLib.init();
    // Application *support*, not documents: this data is app-private and
    // should not be exposed to the user's file browser or backed up wholesale.
    final dir = await getApplicationSupportDirectory();
    await rust_init.initApp(appDir: dir.path);
    _initialised = true;
  }

  String get coreVersion => rust_init.coreVersion();

  /// Which optional engines this binary shipped with (`local-llm`,
  /// `wasm-exec`, `python-exec`), so the UI can hide what it cannot do.
  List<String> get buildFeatures => rust_init.buildFeatures();

  bool get hasLocalInference => buildFeatures.contains('local-llm');

  /// Releases model weights and preview servers when Android backgrounds us.
  Future<void> onPaused() => rust_init.onAppPaused();

  Future<void> setSetting(String key, String value) =>
      rust_init.setSetting(key: key, value: value);

  Future<String?> getSetting(String key) => rust_init.getSetting(key: key);

  // ---- projects ---------------------------------------------------------

  Future<List<ProjectDto>> listProjects() => rust_projects.listProjects();

  Future<ProjectDto> getProject(String id) =>
      rust_projects.getProject(projectId: id);

  Future<ProjectDto> createProject({
    required String name,
    required String description,
    required String kind,
    required String provider,
    required String modelId,
  }) =>
      rust_projects.createProject(
        name: name,
        description: description,
        kind: kind,
        provider: provider,
        modelId: modelId,
      );

  Future<void> renameProject(String id, String name) =>
      rust_projects.renameProject(projectId: id, name: name);

  /// Repoints a project at a different model or provider mid-conversation.
  /// The transcript and sandbox survive the switch.
  Future<void> setProjectModel(String id, String provider, String modelId) =>
      rust_projects.setProjectModel(
        projectId: id,
        provider: provider,
        modelId: modelId,
      );

  Future<void> deleteProject(String id) =>
      rust_projects.deleteProject(projectId: id);

  Future<List<MessageDto>> listMessages(String projectId) =>
      rust_projects.listMessages(projectId: projectId);

  Future<void> clearConversation(String projectId) =>
      rust_projects.clearConversation(projectId: projectId);

  // ---- agent ------------------------------------------------------------

  /// Runs one turn. The stream always ends with a `done` or `failed` event.
  Stream<rust_agent.AgentEventDto> runAgent({
    required String projectId,
    required String message,
    int maxTokens = 8000,
  }) =>
      rust_agent.runAgent(
        projectId: projectId,
        message: message,
        maxTokens: maxTokens,
      );

  Future<void> cancelAgent(String projectId) =>
      rust_agent.cancelAgent(projectId: projectId);

  // ---- model hub --------------------------------------------------------

  Future<List<OfflineModelDto>> listOfflineModels() =>
      rust_models.listOfflineModels();

  Future<List<CloudModelDto>> listCloudModels() => rust_models.listCloudModels();

  Stream<DownloadProgressDto> downloadModel(String modelId) =>
      rust_models.downloadModel(modelId: modelId);

  Future<void> deleteDownloadedModel(String modelId) =>
      rust_models.deleteDownloadedModel(modelId: modelId);

  Future<void> setDefaultLocalModel(String modelId) =>
      rust_models.setDefaultLocalModel(modelId: modelId);

  Future<void> setApiKey(String provider, String key) =>
      rust_models.setApiKey(provider: provider, key: key);

  Future<bool> hasApiKey(String provider) =>
      rust_models.hasApiKey(provider: provider);

  /// Masked form for display. The key itself never crosses the bridge.
  Future<String?> apiKeyHint(String provider) =>
      rust_models.apiKeyHint(provider: provider);

  Future<void> testApiKey(String provider, String key, String modelId) =>
      rust_models.testApiKey(provider: provider, key: key, modelId: modelId);

  // ---- github -----------------------------------------------------------

  /// Whether a token is stored. Offline and instant, so the settings screen can
  /// render its state before the network answers.
  Future<bool> githubConnected() => rust_github.githubConnected();

  /// Resolves the stored token to an account. Hits the network — a failure here
  /// means the token stopped working, not that none is stored.
  Future<rust_github.GitHubAccountDto> githubAccount() =>
      rust_github.githubAccount();

  /// Validates and stores a personal access token. An empty string disconnects.
  Future<rust_github.GitHubAccountDto> connectGithub(String token) =>
      rust_github.connectGithub(token: token);

  /// Brings a branch into a VON without pushing anything back.
  Stream<rust_github.GitHubPushEventDto> pullFromGithub({
    required String projectId,
    required String repo,
    String branch = 'main',
  }) =>
      rust_github.pullProjectFromGithub(
        projectId: projectId,
        repo: repo,
        branch: branch,
      );

  /// Syncs a VON with a branch and commits the merged result. The stream always
  /// ends with a `done` or `failed` event.
  Stream<rust_github.GitHubPushEventDto> pushToGithub({
    required String projectId,
    required String repo,
    String branch = 'main',
    String message = '',
    bool private = true,
  }) =>
      rust_github.pushProjectToGithub(
        projectId: projectId,
        repo: repo,
        branch: branch,
        message: message,
        private: private,
      );

  // ---- device -----------------------------------------------------------

  Future<DeviceProfileDto> runBenchmark({int durationMs = 5000}) =>
      rust_device.runDeviceBenchmark(durationMs: BigInt.from(durationMs));

  DeviceProfileDto? get cachedDeviceProfile => rust_models.cachedDeviceProfile();

  DeviceStatsDto get deviceStats => rust_device.deviceStats();

  Stream<DeviceStatsDto> watchDeviceStats() => rust_device.watchDeviceStats();

  /// Empty string means "go ahead"; anything else is the reason the task is
  /// blocked on this hardware (PRD Page 4).
  Future<String> checkTaskAllowed({
    required String weight,
    required String provider,
  }) =>
      rust_device.checkTaskAllowed(weight: weight, provider: provider);

  // ---- files ------------------------------------------------------------

  Future<List<FileEntryDto>> fileTree(String projectId) =>
      rust_files.fileTree(projectId: projectId);

  Future<String> readFile(String projectId, String path) =>
      rust_files.readProjectFile(projectId: projectId, path: path);

  /// Returns the number of bytes written. `.toInt()` rather than a raw cast:
  /// frb maps Rust `i64` to `PlatformInt64`, which is an `int` natively and a
  /// `BigInt` on web — `.toInt()` is valid on both.
  Future<int> writeFile(String projectId, String path, String content) async {
    final written = await rust_files.writeProjectFile(
      projectId: projectId,
      path: path,
      content: content,
    );
    return written.toInt();
  }

  Future<void> deleteFile(String projectId, String path) =>
      rust_files.deleteProjectFile(projectId: projectId, path: path);

  Future<SandboxUsageDto> sandboxUsage(String projectId) =>
      rust_files.sandboxUsage(projectId: projectId);

  /// Zips the sandbox and returns the archive path for the share sheet.
  /// Copies a picked file into the VON's `uploads/` folder and returns the
  /// sandbox path it landed at.
  Future<String> importFile({
    required String projectId,
    required String fileName,
    required Uint8List bytes,
  }) =>
      rust_files.importFile(
        projectId: projectId,
        fileName: fileName,
        bytes: bytes,
      );

  /// Whether this path is converted rather than read directly, and so cannot
  /// be edited in place.
  Future<bool> isDocument(String path) => rust_files.isDocument(path: path);

  Future<String> exportProject(String projectId) =>
      rust_files.exportProject(projectId: projectId);

  Future<int> clearExports() => rust_files.clearExports();

  // ---- preview ----------------------------------------------------------

  Future<String> startPreview(String projectId) =>
      rust_preview.startPreview(projectId: projectId);

  Future<void> stopPreview(String projectId) =>
      rust_preview.stopPreview(projectId: projectId);

  String? previewUrl(String projectId) =>
      rust_preview.previewUrl(projectId: projectId);

  Future<void> stopAllPreviews() => rust_preview.stopAllPreviews();
}
